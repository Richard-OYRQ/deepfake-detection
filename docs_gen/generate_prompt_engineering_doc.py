def cn(text):
    _char_count[0] += sum(1 for c in text if "\u4e00" <= c <= "\u9fff")
    return text


def set_font(run, size=10.5, bold=False, ea="宋体", ascii_f="Times New Roman",
             color=None):
    run.font.size = Pt(size)
    run.bold = bold
    run.font.name = ascii_f
    run._element.rPr.rFonts.set(qn("w:eastAsia"), ea)
    if color:
        run.font.color.rgb = RGBColor(*color)


def add_para(doc, text, size=10.5, bold=False, align=None, style=None,
             space_after=6, ea="宋体"):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(cn(text))
    set_font(r, size=size, bold=bold, ea=ea)
    return p


def add_heading(doc, text, level=1):
    p = doc.add_heading(level=level)
    r = p.add_run(cn(text))
    set_font(r, size={1: 14, 2: 12}.get(level, 11), bold=True, ea="黑体",
             ascii_f="Arial", color=(0x1F, 0x3B, 0x63))
    return p


def shade(cell, hex_color="D9E2F3"):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def add_table(doc, header, rows, widths=None, font_size=9):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(header):
        c = t.rows[0].cells[j]
        c.text = ""
        r = c.paragraphs[0].add_run(cn(h))
        set_font(r, size=font_size, bold=True, ea="黑体")
        shade(c)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.rows[i + 1].cells[j]
            c.text = ""
            r = c.paragraphs[0].add_run(cn(str(val)))
            set_font(r, size=font_size, ea="宋体")
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Pt(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


