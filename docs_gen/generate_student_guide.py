set_font(p.add_run('——给初中同学的项目实践入门指南'), size=12, color=(0x66, 0x66, 0x66))

# ============ 一、我们想做什么 ============
h1(doc, '一、我们想做什么')
para(doc, '现在有一种AI技术叫"换脸"，可以把视频里一个人的脸换成另一个人的脸。换出来的视频看起来和真的一模一样，普通人很难发现。我们的任务是做一个"AI鉴定小助手"：给它一段视频，它能判断这段视频里的脸是真的还是被换过的。')
para(doc, '我们手里有200个已知答案的视频（100个真视频、100个换脸视频），就像一个带标准答案的练习册——我们做的每一个改进，都可以马上用这200个视频"对答案"，看看准确率是升了还是降了。这就是项目最重要的规矩：不靠感觉，靠数据说话。')

# ============ 二、我们最初的思路 ============
h1(doc, '二、我们最初的思路：让AI当侦探')
para(doc, '我们选用了一款"会看视频的AI"——通义千问视觉大模型。它的用法是：你写一段话（叫"提示词"）告诉它该怎么检查视频，它就会按照你的话去"看"视频，然后回答。比如我们告诉它："请检查视频里人物的脸部边缘是否模糊、肤色是否自然、眨眼是否正常……最后告诉我这是不是换脸视频。"')
para(doc, '我们还给它配了一个"尺子"助手：用传统程序（OpenCV）测量画面的清晰度、脸部和脖子的清晰度差异等数字，把这些数字一起告诉AI，帮它判断。这个思路叫"AI看语义、程序量像素"，两个帮手分工合作。')

# ============ 三、我们做了什么 ============
h1(doc, '三、我们做过的四件大事')
para(doc, '第一件事：选模型。我们测试了四个千问模型，发现它们性格完全不同：有的太胆小（什么都说是真的），有的太冲动（把真视频也说成假的）。最后选中了判断最均衡的一个。这件事让我们明白：工具选对了，后面才能事半功倍。')
para(doc, '第二件事：打磨提示词。我们试了21项检查、14项、18项等多个版本，发现检查项不是越多越好——21项时AI反而什么都看不出来了（就像考试题太多学生乱答）。最后定在14项，再加上后来新增的2个"物理铁证"检查项（遮挡物破坏、转头变形），成了现在的16项版本。')
para(doc, '第三件事：给系统加"外援"。我们发现AI对低清视频里的假脸"看瞎了"，于是让传统程序上场：用像素测量来抓两类"物理上不可能造假"的痕迹——话筒、字幕被假脸破坏的痕迹，以及转头时脸部抖动的痕迹。这三个最难找的假视频，就是被程序的"尺子"抓住的。')
para(doc, '第四件事：自己造假视频做"对照实验"。我们安装了换脸软件FaceFusion，用真实视频造出了14段"和自己一模一样的换脸版"——同一段视频，一真一假，唯一的区别就是换脸。这个"配对实验"让我们发现了一个重要事实：AI侦探对高质量的1080P换脸也识别不出来（两个模型都只猜对了三分之一，和抛硬币差不多）。')

# ============ 四、我们遇到了什么困难 ============
h1(doc, '四、我们遇到了什么困难')
bullet(doc, 'AI侦探"看瞎"问题：低清假视频里的破绽只有几个像素大，AI看不见，还一本正经地编造"话筒边缘锐利完整"这种假答案——它看不见的时候不会说"看不见"，而是会瞎编。')
bullet(doc, '数据"陷阱"问题：我们的假视频恰好都比较模糊、比较短，真视频都比较高清。一开始系统"考高分"（97.5%），后来发现它可能是在靠"模糊不模糊、长不长"来判断，而不是真的认出了换脸——就像考试靠笔迹猜答案而不是会做题。')
bullet(doc, '提示词"无效"问题：换了各种说法、各种格式（保守的、激进的、让AI打分不判案的），AI的判断始终和抛硬币差不多。我们最后确认：不是提示词写得不好，是这款AI对高质量换脸确实"看不出区别"。')

# ============ 4.5 三个故事 ============
h1(doc, '四·五、印象最深的三个小故事')
para(doc, '故事一：AI侦探编瞎话。我们把两张"帧差热力图"（显示画面哪里在动的彩色图）发给AI当证据，它居然一本正经地写："图2四帧转动序列中，鼻尖、唇角、眼距轨迹平滑连续……"——可那根本不是人脸照片，是热力图！我们这才明白：AI看不见的时候不会说"我看不见"，而是会编一个像模像样的答案。从此我们养成了一个习惯：AI说的每句话都要想办法验证。')
para(doc, '故事二：一次"假进步"。有一天我们发现系统的准确率从85.5%跳到97.5%，大家都挺高兴。后来用配对实验一查，发现那多出来的分数是AI靠"视频模糊不模糊"猜出来的——我们的假视频恰好都比较模糊。就像考试时发现学生不是会做题，而是发现"答案长的选项多选C"。这件事教会我们：分数高不一定是真的变强了，要弄清楚分数是从哪来的。')
para(doc, '故事三：换脸软件"装不上"的马拉松。我们想自己造假视频做实验，装FaceFusion折腾了快两天：有个假的安装包、依赖装错了位置、图像库版本冲突、缺了个叫ffmpeg的工具、好不容易跑通了它又"静默失败"（不报错但没换脸）。最后我们学会了三招：给每个工具建"独立小房间"（虚拟环境）、给每次产出做"独立验证"（不信任工具自说自话）、把排查过程写成清单。这三招在真实工作中比任何算法知识都常用。')

# ============ 五、我们学到了什么 ============
