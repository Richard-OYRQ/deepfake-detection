# ============ 十二、问题与思考 ============
h1(doc, '十二、实践中的关键问题与思考')
h2(doc, '12.1 "模型看得见吗"——三层次分辨')
para(doc, '实践中反复出现的一个问题是"模型为什么看不见"。最终通过实验将其分解为三个层次：第一层，信息在不在输入里——低清视频（540P、70px人脸）上像素级伪影的信息物理性缺失，任何模型都无从看起；第二层，信息在不在模型表征里——1080P静帧实验证明，即使输入信息完整，模型的token化编码也会丢弃细纹理统计，表征层面就没有这些信息；第三层，信息能不能被问出来——CV可视化实验证明，当信息被重编码为模型表征支持的形态（大尺度颜色模式）后，提示词才能有效地"问"出结论。这三个层次的划分直接指导了最终的架构设计：CV负责前两层（测量+重编码），模型负责第三层（核验）。')
h2(doc, '12.2 数据红利与真能力的区分')
para(doc, '系统正确率从54.5%到97.5%的提升中，哪些是真能力、哪些是数据红利？配对基准给出了严格的分解：自适应路由的增益主要来自数据集"伪造全部低清"的分布事实（数据红利，对抗性脆弱）；证据子分的增益完全来自源质量混淆（幻觉信号，已证伪）；CV物理特征与软化系指纹经配对验证（真能力）；CV可视化核验在两轮复现中保持46%/93%（真能力但强度有限）。这一分解的意义在于：结题时展示的97.5%必须连同其构成一起呈现——诚实地指出其中哪些部分在真实场景可迁移、哪些不可，这比单一数字更能体现实践训练的目的。')
