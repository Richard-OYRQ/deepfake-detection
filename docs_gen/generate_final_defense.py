para(doc, '以事后视角审视若干关键决策点：如果提示词调优一开始就用真假双组对照，"宁可错杀"偏置会在两周内暴露；如果数据集源级断层核查提前到特征挖掘之前，"证据子分"幻觉不会进入生产；如果CV可视化注入在首次视觉通道失败后立即尝试，模型通道结论会提前四天被修正；如果工具链从第一天就严格隔离，两天的环境踩坑可压缩到半天。这些反事实的共同指向：项目的瓶颈从来不是模型能力或算法复杂度，而是评估装置与工程纪律的建设时机——它们迟到的每一周，都对应着一批被混淆数据误导的结论。')

