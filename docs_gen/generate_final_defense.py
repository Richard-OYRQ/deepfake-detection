h1(doc, '五、核心技术创新点')
h2(doc, '5.1 物理不可能性证据')
para(doc, '提出并实现"物理不可能性证据"概念：遮挡破坏（话筒、字幕等遮挡物被换脸破坏）与转动连续性破坏（转头过程面部几何跳变）两类伪影在真实拍摄中物理上无法产生，不依赖统计学习即可构成高特异性证据。对应的CV实现为遮挡边缘衰减（人脸内外强边缘梯度比，全表秩基AUC 0.87）与人脸框位移/尺寸抖动。该概念成功捕获了视觉大模型完全漏检的三个隐形伪造样本（F89/F97/F99），先验从0.43-0.51跃升至0.96/0.74/0.84。')
h2(doc, '5.2 双先验融合与稳定化机制')
para(doc, '新旧两个逻辑回归先验模型并行计算取高值的max融合策略，解决了"单一模型换代顾此失彼"的问题：旧模型覆盖视觉可辨伪影、新模型覆盖物理一致性伪影，融合后检出100%、误报14%。配套的稳定化机制（进程内缓存+三次计算取中位数）消除了视频解码非确定性（单次先验波动±0.2），使先验值在路由、注入与终裁三个环节严格一致。')
h2(doc, '5.3 自适应路由')
para(doc, '基于"模型在高清可见、低清失明；CV在低清有信息"的分工事实，按分辨率将检测通道分流：720P以上由模型保守票直接终裁（该票对真实视频特异性极高，正确放行19个CV误伤），低清由CV先验主判+控方捞回。该设计使纯内容特征约束下的正确率从75.0%提升至85.5%，硬误报从24降至3。')
h2(doc, '5.4 CV可视化注入（八组实验的唯一阳性）')
para(doc, '通过八组对照实验发现：模型对换脸外观指纹的感知盲区与提示词人格、任务形式、输入形态均无关（连验证指向明确的断言都做不到，原生高清静帧16/16无法判定），唯一有效的方式是让CV把测量结果重编码成模型能感知的大尺度视觉模式——纹理密度热力图与面颈清晰度剖面曲线。证据图将模型注意力锚定到目标区域并启动感知模式，使模型在46%的假脸上确认面颈纹理跳变（真视频仅7%误确认，两轮复现）。该发现将模型在系统中的角色从"检测器"修正为"被CV教过之后的核验员"。')
