# -*- coding: utf-8 -*-
"""生成《向指导老师的工作汇报》（初二学生口吻，含知识备注与求教问题）。"""
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn


def set_font(run, name='微软雅黑', size=11, bold=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def h1(doc, text):
    p = doc.add_heading(level=1)
    set_font(p.add_run(text), size=15, bold=True, color=(0x1F, 0x4E, 0x79))


def h2(doc, text):
    p = doc.add_heading(level=2)
    set_font(p.add_run(text), size=12.5, bold=True, color=(0x2E, 0x74, 0xB5))


def para(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(22)
    set_font(p.add_run(text), size=11)
    return p


def note(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(0)
    set_font(p.add_run('【知识备注】' + text), size=9.5, color=(0x8B, 0x45, 0x13))
    return p


def bullet(doc, text):
    p = doc.add_paragraph(style='List Bullet')
    set_font(p.add_run(text), size=11)


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Light Grid Accent 1'
    for j, htext in enumerate(headers):
        cell = t.rows[0].cells[j]
        set_font(cell.paragraphs[0].add_run(htext), size=10, bold=True)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            set_font(cell.paragraphs[0].add_run(str(val)), size=10)
    doc.add_paragraph()


doc = Document()

p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
set_font(p.add_run('DeepFake视频鉴伪项目：向指导老师的工作汇报'), size=18, bold=True)
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
set_font(p.add_run('汇报人：欧阳润谦  |  汇报周期：2026年8月3日—8月29日'), size=10.5, color=(0x66, 0x66, 0x66))

# ============ 一、概述 ============
h1(doc, '一、这段时间我做了什么')
para(doc, '8月3日之前，我的检测对象只有100个换脸伪造视频，系统对伪造视频的检出率达到91%，当时我觉得效果还不错。8月3日之后，按照课程要求，我又加入了100个真实视频作为检测对象——就是这一加，暴露了一个大问题：系统把100个真实视频里的82个都误判成了"伪造"！误报率高达82%。这段时间的全部工作，就是围绕"把误报降下来、同时尽量不漏掉真正的伪造"这个目标展开的。经过一个月反复调整，现在系统的综合正确率达到了80%以上，三分类模式下对真实视频的硬性误报降到了0个。下面向老师汇报这个过程，以及我在过程中遇到的不理解和想请教的问题。')
note(doc, '误报=把真实视频错判成伪造；漏检=把伪造视频错判成真实。这两个指标是"跷跷板"，压下一个往往翘起另一个，这是我这个月体会最深的一件事。')

# ============ 二、调整过程 ============
h1(doc, '二、发现问题后的调整过程（也走了不少弯路）')
h2(doc, '2.1 第一次大调整：让AI"别太严格"')
para(doc, '面对82%的误报，我最初的想法很直接：提示词里让AI别那么严格就行了。AI助手推荐我把提示词改造成"无罪推定"原则——默认相信视频是真的，只有发现确凿证据才判伪造；还建议我加一张"美颜滤镜与换脸特征对照表"，让AI先学会区分美颜和换脸。我照做了，结果真实视频的误报确实从82%降到了0，我当时特别高兴。但很快发现跷跷板翻到了另一边：伪造视频的检出几乎归零——AI变得什么都不敢判了，46%的伪造被硬性漏检、54%进了"存疑"等待人工复核。这是我走的第一个弯路：从一个极端摆到了另一个极端。')
note(doc, '提示词=写给AI看的"检查说明书"，告诉它检查哪些项目、怎么判断。AI会严格照着说明书做，说明书写得严它就"宁可错杀"，写得宽它就"从不定罪"。')
h2(doc, '2.2 第二次大调整：让AI当"控方"抓漏检')
para(doc, '为了把漏掉的伪造抓回来，AI助手推荐了"对抗投票"方案：先用宽松的提示词初筛，判"无伪造"的视频再用一份旧的激进提示词（我给它起名"控方"）复查一遍，控方专门找可疑之处。这个方案确实捞回了不少漏检的伪造，但控方太激进了——它把很多真实视频也一起"定罪"。最后我只能规定：控方的意见只能把视频送进"存疑"（交人工复核），不能直接判伪造。这是第二个弯路：给系统加了一个太冲动的角色，只好用规则拴住它。')
h2(doc, '2.3 第三个弯路：自己造假视频做对照实验，发现AI根本"看不见"')
para(doc, '为了搞清楚AI到底能不能识别换脸，我用开源换脸工具FaceFusion（备注见下）把14段真实视频逐一换脸，做出了14对"一模一样只是脸不同"的对照样本——同一段视频，真版和换脸版，分辨率、场景、光照完全相同。然后让AI来判断哪段是换脸版。结果让我很意外：AI对14对的判断和抛硬币差不多。我又做了更细的实验——把换脸区域的原生高清截图直接发给AI，问它"这个区域有没有伪影"，AI的回答几乎全是"无法判定"。也就是说，**连我肉眼能看到的边缘瑕疵，AI都看不见**。这是我本月最重要的发现，下面第三节单独说。')
note(doc, 'FaceFusion=一种开源换脸软件，输入一张人脸照片和一段视频，就能把视频里的人脸替换掉。我装它费了两天功夫（软件环境冲突等问题），但它让我第一次拥有了"自己做实验样本"的能力。')
h2(doc, '2.4 找到目前有效的办法：OpenCV物理工具+AI配合')
para(doc, '既然AI看不见细小的纹理差异，我就让OpenCV（备注见下）来当"物理测量员"：用它测量面部的纹理密度、清晰度、边缘锯齿等数字特征，再把这些测量结果画成热力图和曲线图给AI看。有意思的是：AI虽然自己测不出这些差异，但**看过图之后，能在部分假脸上"确认"出面颈纹理跳变**（46%的假脸被确认，真实视频只有7%被误确认）。目前的最终方案就是这种分工：OpenCV负责测量和画图，AI负责看图核验和写报告，最后综合判断。加上先验阈值校准、按分辨率分流等调整，系统综合正确率终于稳定在80%以上。')
note(doc, 'OpenCV=一种开源的计算机视觉工具库，可以理解成"给程序配了一把像素尺子"——它能测量画面每个小区域的清晰度、边缘强度、颜色等数值。AI看不到的细微差异，尺子量得出来。')

# ============ 三、重要发现 ============
h1(doc, '三、一个重要的发现：千问视觉大模型存在明显缺陷')
para(doc, '通过一个月的反复实验，我发现通义千问视觉大模型（qwen3-vl-plus）在换脸鉴别上有一个明显的缺陷：**它对像素级的细小纹理伪影不敏感**。具体表现为：①直接问它"有没有伪影"，它几乎都答"无法判定"；②我提示它重点看某个区域，它还是看不见；③它看不见的时候不会老实承认，而是会"编"——有一次它把一张热力图描述成"四帧转动序列"，还编造了五官轨迹分析。这让我意识到：大模型擅长"看懂画面里发生了什么"（语义理解），但不擅长"测量画面里的细微差别"（像素级测量），而换脸恰恰经常只留下细微差别。')
para(doc, '所以我觉得，**单独靠大模型很难精准判断视频真假，需要专用检测器配合**。目前我的方案是用OpenCV物理工具来配合——它确实帮上了忙，但我在查阅资料时了解到，学术界主流的做法是训练专门的CNN（备注见下）检测器，那些专用模型对细微伪影的敏感度比通用大模型强很多。OpenCV的手工测量规则相比CNN深度学习的方法，还是略有不足——CNN能自己从海量数据里学到人没总结出来的特征，而我的物理测量只能依赖我想到的那几个指标。这是我下一步想尝试的方向。')
note(doc, 'CNN=卷积神经网络，一种深度学习模型。专用检测器指专门用大量真假视频训练出来的CNN模型。它与大模型的区别：大模型是"通用学霸"，什么都懂一点；专用CNN是"专科医生"，只练鉴别换脸这一件事。')

