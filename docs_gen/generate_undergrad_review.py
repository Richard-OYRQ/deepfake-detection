h2(doc, '3.8 主要技术挑战')
para(doc, '实践过程中遭遇的技术挑战按其性质可分为三类。第一类是信号混淆：美颜滤镜产生与换脸蒙版高度相似的外观特征，数据集的真假标签与源质量（分辨率/码率/时长）完全纠缠，两类混淆先后制造了"面颈比""证据子分"等多个幻觉信号，最终都靠配对对照实验才被识破。第二类是模型能力边界：视觉大模型对低清视频上的像素级伪影物理性不可见，且看不见时会生成貌似合理的虚假描述（幻觉填充），其流畅的语言输出会掩盖感知失败。第三类是工程可靠性：视频解码非确定性使同一视频的CV特征多次计算出现±0.2的先验波动，特征表逐次重建漂移25%~30%，人脸检测在部分视频上随机失败——这些隐蔽的不确定性需要专门的稳定化工程（多次中位数、进程缓存、可复现随机种子）来对冲。')

