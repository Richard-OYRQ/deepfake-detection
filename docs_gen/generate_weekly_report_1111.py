def head(text):
    h = doc.add_paragraph()
    h.paragraph_format.space_before = Pt(6)
    h.paragraph_format.space_after = Pt(3)
    r = h.add_run(text)
    set_font(r, 12, True, ea="黑体", color=(0x1F, 0x3B, 0x63))


def para(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.first_line_indent = Pt(21)
    r = p.add_run(text)
    set_font(r, 10.5, ea="宋体")


def table(header, rows, widths):
    tb = doc.add_table(rows=1 + len(rows), cols=len(header))
    tb.style = "Table Grid"
    tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htxt in enumerate(header):
        c = tb.rows[0].cells[j]; c.text = ""
        r = c.paragraphs[0].add_run(htxt); set_font(r, 9, True, ea="黑体"); shade(c)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = tb.rows[i + 1].cells[j]; c.text = ""
            r = c.paragraphs[0].add_run(str(val)); set_font(r, 9, ea="宋体")
    for j, w in enumerate(widths):
        for row in tb.rows:
            row.cells[j].width = Pt(w)


