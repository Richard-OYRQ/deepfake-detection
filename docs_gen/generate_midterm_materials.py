def build(tier):
    doc = Document()
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(cn("深度伪造检测实践项目")); set_font(r, 20, True, ea="黑体", ascii_f="Arial")
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(cn("中期材料")); set_font(r, 20, True, ea="黑体", ascii_f="Arial")
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(cn("（" + tier.upper() + "版 · 2026年10月）"))
    set_font(r, 10.5, ea="楷体", color=(0x66, 0x66, 0x66))
    doc.add_paragraph()

    lvl = TIERS[tier]
    sec = sub = 0
    for t, head, paras, table in BLOCKS:
        if TIERS[t] > lvl:
            continue
        if head:
            hlevel, text = head
            if hlevel == 1:
                sec += 1
                sub = 0
                title = "、" .join(["一二三四五六七八九十"[sec - 1], text])
            else:
                sub += 1
                title = f"{sec}.{sub} {text}"
            h = doc.add_heading(level=hlevel)
            r = h.add_run(cn(title))
            set_font(r, size={1: 14, 2: 12}.get(hlevel, 11), bold=True, ea="黑体",
                     ascii_f="Arial", color=(0x1F, 0x3B, 0x63))
        for para in (paras or []):
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.first_line_indent = Pt(21)
            r = p.add_run(cn(para))
            set_font(r, 10.5, ea="宋体")
        if table:
            header, rows, widths = table
            tb = doc.add_table(rows=1 + len(rows), cols=len(header))
            tb.style = "Table Grid"
            tb.alignment = WD_TABLE_ALIGNMENT.CENTER
            for j, htxt in enumerate(header):
                c = tb.rows[0].cells[j]; c.text = ""
                r = c.paragraphs[0].add_run(cn(htxt)); set_font(r, 9, True, ea="黑体"); shade(c)
            for i, row in enumerate(rows):
                for j, val in enumerate(row):
                    c = tb.rows[i + 1].cells[j]; c.text = ""
                    r = c.paragraphs[0].add_run(cn(str(val))); set_font(r, 9, ea="宋体")
            if widths:
                for j, w in enumerate(widths):
                    for row in tb.rows:
                        row.cells[j].width = Pt(w)
            doc.add_paragraph().paragraph_format.space_after = Pt(0)
    out = os.path.join(OUT_DIR, f"20261019_中期材料_{tier.upper()}.docx")
    doc.save(out)
    n = C[0]; C[0] = 0
    print(f"{tier}: {out}（汉字约 {n}，含表格）")


for tier in ("3k", "5k", "8k", "15k"):
    build(tier)
