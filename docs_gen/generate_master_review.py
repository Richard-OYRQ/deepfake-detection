para(doc, '全自动模式的三个稳定漏检样本（F89、F97、F99）成为第五阶段的攻坚目标。经人工逐帧甄别，确认三者的伪影类型：F97/F99属"遮挡破坏"型——换脸时原本挡在人脸前的话筒、字幕文字被替换人脸明显破坏；F89属"转动连续性破坏"型——人物由侧身转向正面的过程中面部出现明显变形与抖动。这两类伪影在真实拍摄中物理上无法产生，是特异性最高的伪造证据，但都是像素级、时序局部性的，恰好落在系统全部信号的单帧静态统计盲区之外。据此提炼出项目最重要的概念性成果之一："物理不可能性证据"——不依赖任何统计学习，而是利用真实世界物理约束构造的检测信号。')
para(doc, '随后进行了两轮视觉通道实验，均为阴性且极具信息量。第一轮从提示词入手：新增"遮挡破坏"与"转动连续性"两条物理不可能性硬证据检查项，明确"确认异常即可单独定罪"。三个视频重跑后仍判无伪造，模型甚至逐项描述"话筒金属网边缘锐利、连续穿过面部"，把伪影反过来当作真实拍摄的证据。第二轮改造送检层：实现事件帧提取器，自动生成遮挡交界放大图、转动序列对比图、帧差增强图随视频混装送检。模型确实收到了证据图并逐张引用，但判定不变。最具决定性的证据是F99的一次幻觉：模型把帧差热力图描述成"四帧转动序列"，并据此编造了五官轨迹的连续运动学分析——它在看不到细节时会系统性地填充合理但虚假的"物理一致性完好"描述。这一发现构成了对视觉大模型可靠性边界的最直接证据：模型的流畅表达能力会掩盖其感知失败。')
para(doc, '第三轮转向CV定量特征：实现密集物理扫描，提取遮挡边缘衰减（人脸内外强边缘梯度比）、人脸框位移/尺寸抖动等特征，全量重建200视频特征表并重拟合16特征先验模型。两个发现：遮挡边缘衰减在全表规模成为最强判别特征（秩基AUC 0.87，方向为伪造更高——合成脸相对背景存在"过度锐利"指纹）；三个目标视频的稳定先验从0.43-0.51跃升至0.96/0.74/0.84。但直接换用新模型是零和博弈——新模型漏掉11个旧模型能抓的伪造且视觉通道同样漏检。最终采用双先验max融合：新旧模型并行计算取高值，检出100%、误报14%、综合正确率93.0%，仅比旧模型多1个误报。')
para(doc, '密集物理扫描的技术实现要点：以0.4秒间隔密集采样（上限60帧），逐帧做Sobel边缘检测与Haar人脸检测；遮挡边缘衰减定义为"人脸内中心60%区域强边缘像素梯度中位数与人脸外环带之比"，在边缘密度超过阈值（2%）的帧上计算，取均值与最小值两个统计量；人脸框位移/尺寸抖动定义为相邻帧人脸框中心位移与宽度变化的MAD（按框宽归一），捕捉转动中的几何不稳定。这些特征的设计全部源自对两类物理伪影的机理分析而非数据拟合，其判别力在200视频全表上得到独立验证——机理驱动的特征设计在本项目中表现出远优于数据驱动设计的稳健性。')
para(doc, '阶段内还完成两项工程修复。其一，15.mp4（17.6MB）因base64内联超过API的20MiB data-uri上限被反复拒绝，将客户端阈值从18MB降至15MiB改走文件上传通道后送检成功——这是API集成中典型的隐性体积约束。其二，补跑中该真实视频被控方轮"翻案定罪"（先验0.987触发控方，3票换脸置信96），成为三分类模式下唯一的硬误报，恰好验证了离线校准对误报名单的预测。')

# ============ 七、第六阶段 ============
h1(doc, '七、第六阶段（8月27日）：v5.3—v5.5约束收紧与架构定型')
para(doc, '第六阶段围绕两个新约束展开。第一个约束来自用户明确裁决：待检测视频时长绝对不能作为判断真伪的依据。由此引发全面排查：数据核查发现了数据集的源级断层——真实视频主流1080P、码率均值6.7Mbps，而伪造视频全部不超过960×720、码率上限仅2.0Mbps，F89的人脸仅70像素宽。这解释了模型失明的表面原因，也埋下了一个更深的隐患（将在第七阶段爆发）：数据集真假标签与源质量完全纠缠。经裁决确定约束：时长、分辨率、码率等源级元数据一律不得作为判据，只允许画面内容特征。据此将时长及"有效帧数"（时长的伪装）从先验模型中彻底剔除，仅保留15个纯内容特征。代价是判别力显著下降：纯内容特征的全自动最优正确率降至75.0%。三个目标视频依然受保护。')
para(doc, '为寻找补偿，进行了模型通道信息量的系统性裁决实验，四个实验一致证明：qwen3-vl-plus在该数据集上无论提示词人格、输出格式、思考模式还是证据图都榨不出决策信息——保守票对一切判"无伪造"（零信息）；激进票检出94%但特异性16%（近常量）；旧激进票加入回归后正确率不升反降（82.0%降至80.9%）；"证据分析师"新人格配合思考模式输出校准概率，AUC仅0.530且6/40不按输出格式作答。模型票是噪声，CV主判是信息约束下的必然而非设计偏好。同时发现两个方法学问题：五折交叉验证单次评估噪声可达±17个百分点；特征表逐次重建中物理抖动类特征漂移25%-30%。')
para(doc, '"证据分析师"实验的细节具有独立的方法论价值。该实验为模型设计了全新人格：不给结论任务，只要求盘点证据——16项逐项评级、良性解释排查、证据天平、以及带严格打分规则的校准概率P(伪造)输出（"看不清的项按50分中性处理、禁止猜测"），并开启混合思考模式。结果：伪造组概率均值63.5、真实组62.8，秩基AUC 0.530。这意味着即便把任务改造成最有利于模型的形式——输出校准概率而非二值结论、允许逐步推理——模型依然不能从画面中提取判别信息。结合F99幻觉实验，可以严格地得出结论：模型在该数据上的"盲"不是输出格式或提示词结构的问题，而是输入信息在模型视觉管线中根本未被有效编码。')
para(doc, '随后的突破来自自适应路由思路（v5.4）：按分辨率分流，720P及以上走"模型主导"分支（保守票直接终裁、跳过控方轮、CV冲突豁免），低清走"CV主导"分支。数据结构完美支撑：真实组93%达720P以上，伪造组0%。离线模拟显示全自动正确率从75.0%升至85.5%——24个CV误报中的19个高清真实视频被模型票正确放行。最后是v5.5的控方证据子分：从控方轮输出的逐项证据表中挖掘7个分离性单项的"异常"计数，48段校准样本中CV漏检伪造24/26子分≥3、低先验真实2/10，全自动模拟正确率达97.5%，首次越过90%目标。当时将其归功于"模型逐项观察的量化信号"——这个归因将在第七阶段被配对实验推翻，但该阶段的架构形态（双分支路由+多信号终裁）被保留了下来。')

# ============ 八、第七阶段 ============
h1(doc, '八、第七阶段（8月27—28日）：配对基准集建设与模型能力边界的确立')
para(doc, '第七阶段的起点是一个尖锐的方法论质疑：当前数据集真假标签与源质量（分辨率/码率/时长）完全纠缠，任何"检测发现"都可能是源质量差异的产物，无法科学地完成提示词工程定型。这一质疑完全正确，并直接催生了项目最重要的实验装置——配对基准集。')
para(doc, '配对基准集的构建思路：取真实视频，用FaceFusion（现代单图换脸工具，inswapper模型）将其人脸替换为exface目录中的其他人物，生成"同一段视频的换脸版"。配对样本与原视频共享分辨率、码率、内容、光照——唯一差异是换脸本身。这是把混淆变量从实验里连根拔除的设计，与FaceForensics++等学术数据集的构建方法论一致。工程上经历了一条典型的踩坑链：PyPI上的facefusion包为占位包（0.0.0版本，名称被抢注）；官方install.py调用PATH中的pip把依赖装进了项目环境而非目标环境；opencv-python-headless 5.0移除了CascadeClassifier导致项目人脸检测一度瘫痪（最终通过为FaceFusion建立独立venv钉死5.0、项目环境恢复4.14解决）；ffmpeg/ffprobe缺失且winget拉取缓慢（从npmmirror的ffmpeg-static镜像下载便携版解决）；部分视频换脸静默失败（通过60帧探针筛选出20个目标视频中16个可换）。')
para(doc, '换脸静默失败的排查过程本身就是一堂完整的排障方法课。现象：管线全程无报错、输出视频与原视频几乎一致。依次排除的假设包括：换脸模型问题（hyperswap换inswapper无效）、人脸选择模式问题（one/reference/many均无效）、参考距离过滤问题（放宽到1.5无效）、人脸检测器问题（yolo_face换yunet无效）、源脸质量问题（用已成功视频的人脸帧当源脸仍无效）。最终通过"二分定位实验"确定问题在目标视频侧，再通过批量探针确定20个目标中16个可换、4个顽固失败——证明是部分视频与FaceFusion分析管线的兼容性问题，而非配置错误。这一排查链的核心教训：静默失败（无报错但结果错误）是最危险的失败模式，必须有独立于工具链的验证手段——本项目为此专门实现了"输出帧vs原视频同帧直接比对"验证法，以人脸区与背景区像素差的比值判定换脸是否真正发生。')
para(doc, '在配对基准上，此前所有"模型通道有效"的结论被逐一证伪。保守票0/14检出；控方整体票假脸10/14、真视频10/14——零判别力；控方证据子分假脸均值1.9 vs 真视频2.1——v5.5归功于"模型逐项观察"的信号在干净数据上完全蒸发；逐项异常率每一项都无分离。两个模型（qwen3-vl-plus与qwen-vl-max）在3对样本上正确率同为2/6，错误模式互补但都不具备判别力——vl-max错在过度定罪（把两个真视频判换脸、置信95），vl-plus错在完全失敏（把三个假视频全部放过、置信一律96）。结论必须修正：此前"模型失明源于低分辨率"的归因不成立——1080P输入信息完整，模型依然无法区分换脸与原件。模型对换脸外观痕迹的判别力缺失是普遍性的，低分辨率只是像素级伪影的加重因素。')
para(doc, 'v5.5证据子分被证伪的过程值得作为完整案例记录：该信号从控方轮输出的逐项证据表中挖掘7个"分离性单项"（面部拉伸、肤色帧间波动、毛发边缘、微表情、帧间突变、颈部色差、耳朵扭曲）的异常计数，在48段校准样本上表现出极强的表面判别力（CV漏检伪造24/26子分≥3、低先验真实2/10），据此被纳入生产终裁并贡献了97.5%正确率中的关键增量。配对基准的14对数据给出了相反的判决：假脸子分均值1.9、真视频2.1、成对差值-0.1。回顾其成因：低清伪造视频因整体画质劣化，控方模型在多项检查上更倾向于标"异常"，与换脸无关——源质量混淆又一次制造了幻觉信号。该案例与"面颈比"假说（美颜混淆）、"遮挡边缘比"假说（全表与小样本方向反转）共同构成项目中最具教育意义的三次"信号证伪"，深刻说明了评估集质量决定结论质量的道理。')
para(doc, '但同批实验给出了一个反转性的积极信号：CV评估中"面部软化系"特征（面部清晰度、面/背清晰比、面/颈比、噪声残留比）在3对样本上方向100%一致——换脸重绘使面部纹理软化、细节减少，这是换脸本身的像素指纹，与源质量无关。模型看不见它，传统CV能测到。这是当前唯一在配对基准上表现出方向一致性的信号，也是后续判定策略最重要的候选基础。')

