h2(doc, '6.1 关于"模型看得见吗"的三层次分辨')
para(doc, '实践中反复出现的问题是"模型为什么看不见"。最终通过实验将其分解为三个层次：第一层，信息在不在输入里——低清视频（540P、70px人脸）上像素级伪影的信息物理性缺失，任何模型都无从看起；第二层，信息在不在模型表征里——1080P静帧实验证明，即使输入信息完整，模型的token化编码也会丢弃细纹理统计，表征层面就没有这些信息；第三层，信息能不能被问出来——CV可视化实验证明，当信息被重编码为模型表征支持的形态（大尺度颜色模式）后，提示词才能有效地"问"出结论。这三个层次的划分直接指导了最终的架构设计：CV负责前两层（测量+重编码），模型负责第三层（核验）。')
